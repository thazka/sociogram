// Server rendering must never touch the browser: no window, no navigator, no
// HTMLElement, no WebAssembly engine. These run in plain Node, where all of
// those are absent, which is exactly the environment of Next.js and Nuxt on the
// server.

import { existsSync } from "node:fs";
import { createElement } from "react";
import { renderToString } from "react-dom/server";
import { createSSRApp, h } from "vue";
import { renderToString as renderVue } from "vue/server-renderer";
import { describe, expect, it } from "vitest";

describe("server rendering", () => {
  it("runs in an environment without a browser", () => {
    expect(typeof window).toBe("undefined");
    expect(typeof navigator === "undefined" || !("gpu" in navigator)).toBe(true);
    expect(typeof HTMLElement).toBe("undefined");
  });

  it("renders the React component to markup without touching the browser", async () => {
    const { Sociogram } = await import("../src/react.js");
    const html = renderToString(
      createElement(Sociogram, {
        data: { nodeCount: 2, edges: [0, 1] },
        className: "graph",
        style: { height: 300 },
        fallback: createElement("p", null, "no WebGPU"),
      }),
    );
    expect(html).toContain('class="graph"');
    expect(html).toContain("height:300px");
    expect(html).not.toContain("<canvas"); // the canvas only exists in the browser
    expect(html).not.toContain("no WebGPU"); // the fallback appears only after a failed create
  });

  it("renders the Vue component to markup without touching the browser", async () => {
    const { Sociogram } = await import("../src/vue.js");
    const app = createSSRApp({
      render: () => h(Sociogram, { data: { nodeCount: 2, edges: [0, 1] }, class: "graph" }),
    });
    const html = await renderVue(app);
    expect(html).toContain("<div");
    expect(html).not.toContain("<canvas");
  });

  it("imports the Web Component module on the server", async () => {
    const mod = await import("../src/element.js");
    expect(typeof mod.defineSociogramElement).toBe("function");
  });

  it("refuses to register the element outside a browser, with a clear message", async () => {
    const { defineSociogramElement } = await import("../src/element.js");
    expect(() => defineSociogramElement()).toThrow(/browser/);
  });

  // The entry point re-exports the engine, whose glue is generated by `npm run build:wasm`.
  it.skipIf(!existsSync(new URL("../src/wasm/sociogram_web.js", import.meta.url)))(
    "imports the package entry point on the server (needs `npm run build:wasm`)",
    async () => {
      const mod = await import("../src/index.js");
      expect(typeof mod.mountSociogram).toBe("function");
      expect(typeof mod.SociogramView).toBe("function");
    },
  );
});
